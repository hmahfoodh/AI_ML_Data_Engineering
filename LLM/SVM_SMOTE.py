def min_max_scale_lists(model_data):
   """
   Applies Min-Max scaling (normalization) across multiple lists of data.


   The scaling is based on the global minimum (min) and maximum (max) values
   found across ALL the provided lists combined.


   The formula used is: X_scaled = (X - X_min) / (X_max - X_min)


   Args:
       model_data (list of lists): A list where each inner list represents
                                   a feature's values from a different model.
                                   Example: [[model1_data], [model2_data], ...]


   Returns:
       list of lists: The original lists, now containing the normalized values
                      between 0 and 1.
   """
   if not model_data or not any(model_data):
       # Handle empty input case
       return []


   # 1. Flatten the list of lists into a single NumPy array
   # We use NumPy because it is optimized for numerical operations like finding min/max
   flat_array = np.concatenate([np.array(lst) for lst in model_data])


   # 2. Calculate the global minimum (X_min) and maximum (X_max)
   x_min = np.min(flat_array)
   x_max = np.max(flat_array)


   # Calculate the range (denominator)
   data_range = x_max - x_min


   # Handle the case where all elements are the same (range is zero)
   if data_range == 0:
       # If the range is 0, all scaled values should be 0.5 (or 0, depending on context,
       # but 0.5 is safe for this formula's intent)
       print("Warning: All data points are identical. Returning lists of 0.5.")
       return [[0.5 for _ in lst] for lst in model_data]


   # 3. Apply the scaling transformation to each individual list
   scaled_data = []
  
   for original_list in model_data:
       # Convert the current list to a NumPy array for vectorized calculation
       current_array = np.array(original_list)
      
       # Apply the Min-Max formula element-wise
       scaled_array = (current_array - x_min) / data_range
      
       # Convert the resulting scaled NumPy array back to a standard Python list
       scaled_data.append(scaled_array.tolist())
      
   return scaled_data


def remove_english_chars(input_string: str) -> str:
   """
   Removes all English alphabet characters (A-Z and a-z) from the input string.
   """
   cleaned_string = re.sub(r'[a-zA-Z]', '', input_string)
   return cleaned_string


# Function to calculate G-Mean (Geometric Mean of Class Recalls)
def calculate_g_mean(y_true, y_pred):
   """Calculates the Geometric Mean of Recall for each class."""
   _, recall_per_class, _, _ = precision_recall_fscore_support(
       y_true, y_pred, average=None, zero_division=0
   )
   # Filter out zero recalls
   recall_per_class = recall_per_class[recall_per_class > 0]
   if len(recall_per_class) == 0:
        return 0.0
       
   g_mean = np.prod(recall_per_class)**(1.0 / len(recall_per_class))
   return g_mean


# Function to calculate and print class percentages
def print_class_percentages(y_array, title):
   """Calculates and prints the percentage distribution of classes."""
   counts = Counter(y_array)
   total = len(y_array)
   print(f"\n--- {title} ---")
   for cls in sorted(counts.keys()):
       count = counts[cls]
       percentage = (count / total) * 100
       print(f"Class {cls}: {count} samples ({percentage:.2f}%)")
   print("-" * 35)




